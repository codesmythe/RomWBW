;
;==================================================================================================
;   TTY EMULATION MODULE
;==================================================================================================
;
		DEVECHO	"TTY:"
		DEVECHO " ENABLED"
		DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_TTY	.EQU	$
;
	.DW	SIZ_TTY			; MODULE SIZE
	.DW	TTY_INITPHASE		; ADR OF INIT PHASE HANDLER
;
TTY_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,TTY_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,TTY_INIT		; DO INIT
	RET				; DONE
;
; PRE-CONSOLE INITIALIZATION
;
TTY_PREINIT:
	OR	$FF			; CLEAR
	LD	(TTY_VDAUNIT),A		; ... VDA UNIT
	LD	(TTY_KBDUNIT),A		; ... AND KEYBOARD UNIT
	XOR	A
	RET
;
; INITIALIZATION OF EMULATION MODULE
;
TTY_INIT:
;
; ADD OURSELVES TO CIO DISPATCH TABLE
;
	XOR	A			; FOR NOW, ASSUME
	LD	(TTY_VDAUNIT),A		; ... VDA AND KBD UNITS
	LD	(TTY_KBDUNIT),A		; ... ARE UNIT #0
;
	; ANNOUNCE
	CALL	NEWLINE
	PRTS("TTY:$")
	PRTS(" VDA=$")
	LD	A,(TTY_VDAUNIT)
	CALL	PRTDEC8
	PRTS(" KBD=$")
	LD	A,(TTY_KBDUNIT)
	CALL	PRTDEC8
;
	; INIT/RESET OUR INTERNAL STATE
	CALL	TTY_RESET		; FULL RESET OF EMULATOR INTERNAL STATE
	RET	NZ			; BAIL OUT ON ERROR
;
	; REGISTER AS CHARACTER DEVICE
	LD	IY,TTY_IDAT		; POINTER TO INSTANCE DATA
	LD	DE,TTY_IDAT		; DE := INSTANCE DATA PTR
	CALL	CIO_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED
	LD	(IY+CFG_UNIT),A		; RECORD HBIOS UNIT NUMBER ASSIGNED
	CALL	CIO_SETCRT		; SET OURSELVES AS THE CRT DEVICE
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
; INSTANCE DATA
;
TTY_IDAT:
	.DW	TTY_FNTBL		; DRIVER FUNCTION TABLE ADDRESS				
	.DB	'C'			; DRIVER TYPE						
	.DB	$FF			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY, $FF=NONE)	
	.DB	0			; DRIVER UNIT NUMBER (ONLY ONE UNIT POSSIBLE)		
	.DB	ERR_NONE		; DEVICE STATUS (HBIOS STATUS)				
	.DW	TTY_STR_TAG		; DRIVER TAG STRING PTR					
;
TTY_STR_TAG	.TEXT	"TTY$"
;
; DRIVER FUNCTION TABLE
;
TTY_FNTBL:
	.DW	TTY_IN
	.DW	TTY_OUT
	.DW	TTY_IST
	.DW	TTY_OST
	.DW	TTY_INITDEV
	.DW	TTY_QUERY
	.DW	TTY_DEVICE
	.DW	CIO_BLKIN
	.DW	CIO_BLKOUT
#IF (($ - TTY_FNTBL) != (CIO_FNCNT * 2))
	.ECHO	"*** INVALID TTY FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
;
;
TTY_VDADISP:
	LD	A,(TTY_VDAUNIT)
	CP	$FF
	JR	Z,TTY_UNITERR
	PUSH	IY
	LD	C,A
	CALL	VDA_DISPATCH
	POP	IY
	RET
;
;
;
TTY_KBDDISP:
	LD	A,(TTY_KBDUNIT)
	CP	$FF
	JR	Z,TTY_UNITERR
	PUSH	IY
	LD	C,A
	CALL	KBD_DISPATCH
	POP	IY
	RET
;
;
;
TTY_UNITERR:
	SYSCHKERR(ERR_NOUNIT)		; INVALID UNIT NUMBER
	RET
;
;
;
TTY_VDARES:
	; RESET THE ATTACHED VDA DEVICE
	LD	A,(TTY_VDAUNIT)
	CP	$FF
	RET	Z
	LD	B,BF_VDARES		; FUNC: RESET
	LD	C,A			; PUT IN C
	JP	HB_DISPATCHP		; CALL THE VDA DRIVER (PRESERVES IY)
;
;
;
TTY_RESET:
	; QUERY THE VIDEO DRIVER FOR SCREEN DIMENSIONS
	LD	B,BF_VDAQRY	; FUNCTION IS QUERY
	LD	HL,0		; WE DO NOT WANT A COPY OF THE CHARACTER BITMAP DATA
	CALL	TTY_VDADISP	; PERFORM THE QUERY FUNCTION
	RET	NZ		; HANDLE ERROR
	LD	(TTY_DIM),DE	; SAVE THE SCREEN DIMENSIONS RETURNED
;
	LD	DE,0		; DE := 0, CURSOR TO HOME POSITION 0,0
	LD	(TTY_POS),DE	; SAVE CURSOR POSITION
;
	XOR	A		; SIGNAL SUCCESS
	RET			; DONE
;
;
;
TTY_IN:
#IF (VDAEMU_SERKBD != $FF)
	LD	C,VDAEMU_SERKBD
	JP	HB_DISPATCHP		; CHAIN TO SERIAL KBD UNIT (PRESERVES IY)
#ELSE
	LD	B,BF_KBDREAD	; SET FUNCTION TO KEYBOARD READ
	JP	TTY_KBDDISP	; CHAIN TO VDA DISPATCHER
#ENDIF
;
;
;
TTY_OUT:
	CALL	TTY_DOCHAR	; HANDLE THE CHARACTER (EMULATION ENGINE)
	XOR	A		; SIGNAL SUCCESS
	RET
;
;
;
TTY_IST:
#IF (VDAEMU_SERKBD != $FF)
	LD	C,VDAEMU_SERKBD
	CALL	HB_DISPATCHP		; SERIAL KBD UNIT STATUS (PRESERVES IY)
	JP	M,TTY_IST1	; HANDLE ERROR
	RET
#ELSE
	LD	B,BF_KBDSTAT	; SET FUNCTION TO KEYBOARD STATUS
	CALL	TTY_KBDDISP	; CALL KBD DISPATCHER
	JP	M,TTY_IST1	; HANDLE ERROR
	RET
#ENDIF
;
TTY_IST1:	; SIMULATE NO KEYS AVAILABLE
	XOR	A
	RET
;
;
;
TTY_OST:
	XOR	A		; ZERO ACCUM
	INC	A		; A := 1 TO SIGNAL OUTPUT BUFFER READY
	RET
;
;
;
TTY_INITDEV:
	; RESET THE ATTACHED VDA DEVICE
	LD	B,BF_VDAINI	; FUNC: INIT
	LD	E,-1		; DO NOT CHANGE VIDEO MODE
	LD	HL,0		; DO NOT LOAD A BITMAP
	CALL	TTY_VDADISP	; CALL THE VDA DRIVER
	; RESET OUR INTERNAL STATE AND RETURN
	JP	TTY_RESET	; RESET OURSELVES AND RETURN
;
;
;
TTY_QUERY:
	LD	DE,(TTY_UNITS)		; D = VDA UNIT, E = KBD UNIT
	XOR	A
	RET
;
;
;
TTY_DEVICE:
	LD	D,CIODEV_TTY		; DEVICE TYPE
	LD	E,(IY+CFG_DEVNUM)	; PHYSICAL UNIT
	LD	C,$C0			; C := ATTRIBUTES, $C0 IS TERMINAL EMULATION
	LD	HL,$FFFF		; NOT DEFINED FOR EMULATORS
	XOR	A			; SIGNAL SUCCESS
	RET
;
;
;
TTY_DOCHAR:
	LD	A,E		; CHARACTER TO PROCESS
	CP	7		; BEL
	JP	Z,SND_BEEP
	CP	8		; BACKSPACE
	JR	Z,TTY_BS
	CP	12		; FORMFEED
	JR	Z,TTY_FF
	CP	13		; CARRIAGE RETURN
	JR	Z,TTY_CR
	CP	10		; LINEFEED
	JR	Z,TTY_LF
	CP	32		; COMPARE TO SPACE (FIRST PRINTABLE CHARACTER)
	RET	C		; SWALLOW OTHER CONTROL CHARACTERS
	LD	B,BF_VDAWRC
	CALL	TTY_VDADISP	; SPIT OUT THE RAW CHARACTER
	LD	A,(TTY_COL)	; GET CUR COL
	INC	A		; INCREMENT
	LD	(TTY_COL),A	; SAVE IT
	LD	DE,(TTY_DIM)	; GET SCREEN DIMENSIONS
	CP	E		; COMPARE TO COLS IN LINE
	RET	C		; NOT PAST END OF LINE, ALL DONE
	CALL	TTY_CR		; CARRIAGE RETURN
	JR	TTY_LF		; LINEFEED AND RETURN
;
TTY_FF:
	LD	DE,0		; PREPARE TO HOME CURSOR
	LD	(TTY_POS),DE	; SAVE NEW CURSOR POSITION
	CALL	TTY_XY		; EXECUTE
	LD	DE,(TTY_DIM)	; GET SCREEN DIMENSIONS
	LD	H,D		; SET UP TO MULTIPLY ROWS BY COLS
	CALL	MULT8		; HL := H * E TO GET TOTAL SCREEN POSITIONS
	LD	E,' '		; FILL SCREEN WITH BLANKS
	LD	B,BF_VDAFIL	; SET FUNCTION TO FILL
	CALL	TTY_VDADISP	; PERFORM FILL
	JR	TTY_XY		; HOME CURSOR AND RETURN
;
TTY_BS:
	LD	A,(TTY_COL)	; GET CURRENT COLUMN
	DEC	A		; BACK IT UP BY ONE
	RET	C		; IF CARRY, MARGIN EXCEEDED, ABORT
	LD	(TTY_COL),A	; SAVE NEW COLUMN
	JP	TTY_XY		; UDPATE CUSROR AND RETURN
;
TTY_CR:
	XOR	A		; ZERO ACCUM
	LD	(TTY_COL),A	; COL := 0
	JR	TTY_XY		; REPOSITION CURSOR AND RETURN
;
TTY_LF:		; LINEFEED (FORWARD INDEX)
	LD	A,(TTY_ROW)	; GET CURRENT ROW
	LD	DE,(TTY_DIM)	; GET SCREEN DIMENSIONS
	DEC	D		; D := MAX ROW NUM
	CP 	D		; >= LAST ROW?
	JR	NC,TTY_LF1	; IF SO, NEED TO SCROLL
	INC	A		; BUMP TO NEXT ROW
	LD	(TTY_ROW),A	; SAVE IT
	JP	TTY_XY		; UPDATE CURSOR AND RETURN
;
TTY_LF1:	; SCROLL
	LD	E,1		; SCROLL FORWARD 1 LINE
	LD	B,BF_VDASCR	; SET FUNCTION TO SCROLL
	JP	TTY_VDADISP	; DO THE SCROLLING AND RETURN
;
TTY_XY:
	LD	DE,(TTY_POS)	; GET THE DESIRED CURSOR POSITION
	LD	B,BF_VDASCP	; SET FUNCTIONT TO SET CURSOR POSITION
	JP	TTY_VDADISP	; REPOSITION CURSOR
;
;
;
TTY_POS:
TTY_COL		.DB	0	; CURRENT COLUMN - 0 BASED
TTY_ROW		.DB	0	; CURRENT ROW - 0 BASED
;
TTY_DIM:
TTY_COLS	.DB	80	; NUMBER OF COLUMNS ON SCREEN
TTY_ROWS	.DB	24	; NUMBER OF ROWS ON SCREEN
;
TTY_UNITS:
TTY_KBDUNIT	.DB	$FF	; UNIT NUM OF ATTACHED KEYBOARD DEVICE
TTY_VDAUNIT	.DB	$FF	; UNIT NUM OF ATTACHED VIDEO DEVICE
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_TTY		.EQU	$
SIZ_TTY		.EQU	END_TTY - ORG_TTY
;	
	MEMECHO	"TTY occupies "
	MEMECHO	SIZ_TTY
	MEMECHO	" bytes.\n"
