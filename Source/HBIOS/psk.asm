;__________________________________________________________________________________________________
; KEYBOARD PRE-INITIALIZATION
;__________________________________________________________________________________________________
;
; TO BE CALLED PRIOR TO INTERRUPTS BEING ENABLED
;
PSK_PREINIT:
	LD	IY,PSK0_IDAT		; POINTER TO INSTANCE DATA
;
#IF (PSKINTS)
	; DISABLE DEVICES (KEYBOARD/MOUSE)
	LD	A,PSK_CON_DP1		; DISABLE PORT 1 (KEYBOARD)
	CALL	PSK_PUTCMD		; SEND IT
	LD	A,PSK_CON_DP2		; DISABLE PORT 2 (MOUSE)
	CALL	PSK_PUTCMD		; SEND IT
;
	; FLUSH ANY PENDING OUTPUT
	LD	B,16			; UP TO 16 BYTES MAY BE WAITING
PSK_PREINIT1:
	CALL	PSK_IN_P		; BLIND READ
	DJNZ	PSK_PREINIT1		; AND LOOP
;
	; DISABLE INTERRUPTS
	LD	A,PSK_CON_WCR		; SET COMMAND REGISTER
	CALL	PSK_PUTCMD		; SEND IT
	LD	A,PSK_CON_IOF		; XLAT DISABLED, MOUSE DISABLED, NO INTS
	CALL	PSK_PUTDATA		; SEND IT
;
#ENDIF
	RET
;
;__________________________________________________________________________________________________
; KEYBOARD INITIALIZATION
;__________________________________________________________________________________________________
;
PSK_INIT:
	LD	B,PSKCNT		; LOOP CONTROL
	LD	IY,PSK_IDAT		; START OF CFG TABLE
PSK_INIT1:	
	PUSH	BC			; SAVE LOOP CONTROL
	CALL	PSK_INITUNIT		; HAND OFF TO GENERIC INIT CODE
	POP	BC			; RESTORE LOOP CONTROL
	LD	DE,PSK_CFGSIZ		; SIZE OF CFG ENTRY
	ADD	IY,DE			; BUMP IY TO NEXT ENTRY
	DJNZ	PSK_INIT1		; LOOP UNTIL DONE
;
	XOR	A
	RET
;
;
;
PSK_INITUNIT:
	CALL	DRV_PRTTAG_NL
	PRTS(" IO=0x$")			; DISPLAY
	LD	A,(IY+PSK_DAT)		; PORT SETTING
	CALL	PRTHEXBYTE
	PRTS(" MODE=$")			; TAG
	LD	A,(IY+PSK_MODE)		; GET MODE VALUE
	LD	DE,PSK_STR_MODE_CVDU
	CP	PSKMODE_CVDU
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_GDC
	CP	PSKMODE_GDC
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_VGA
	CP	PSKMODE_VGA
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_VRC
	CP	PSKMODE_VRC
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_N8PC
	CP	PSKMODE_N8PC
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_RC
	CP	PSKMODE_RC
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_MBC
	CP	PSKMODE_MBC
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_DUO
	CP	PSKMODE_DUO
	JR	Z,PSK_INITUNIT1
	LD	DE,PSK_STR_MODE_UNK
;
PSK_INITUNIT1:
	CALL	WRITESTR
#IF ((INTMODE == 2) & PSKINTS)
	; TODO: INTS ONLY POSSIBLE ON PSK0
	PRTS(" INT #$")			; DISPLAY 	
	LD	A,INT_PS2KB		; INTERRUPT SETTING
	CALL	PRTDECB
#ENDIF
;
	LD	A,PSK_DEFRPT		; GET DEFAULT REPEAT RATE
	LD	(PSK_REPEAT),A		; SAVE IT
	LD	A,PSK_DEFSTATE		; GET DEFAULT STATE
	LD	(PSK_STATE),A		; SAVE IT
;
	LD	A,(IY+PSK_MODE)		; GET PSK MODE BYTE
	CP	PSKMODE_VRC		; VRC?
	JR	Z,PSK_INITUNIT2		; IF SO, MUST ASSUME PRESENT
;
;	HB_DI				; DISABLE INTERRUPTS WHILE WE PROBE
	LD	A,PSK_CON_CST		; CONTROLLER SELF TEST
	CALL	PSK_PUTCMD		; SEND IT
	CALL	PSK_GETDATA_P		; CONTROLLER SHOULD RESPOND WITH $55 (ACK)
;	HB_EI				; RESTORE INTERRUPTS
;
	CP	$55			; IS IT THERE?
	JR	Z,PSK_INITUNIT2		; IF SO, CONTINUE
	PRTS(" NOT PRESENT$")		; DIAGNOSE PROBLEM
	OR	$FF			; SIGNAL FAILURE
	RET				; BAIL OUT
;
PSK_INITUNIT2:
#IF ((INTMODE == 2) & PSKINTS)
	; TODO: INTS ONLY POSSIBLE ON PSK0
;	CALL	PSKQINIT		; INITIALIZE QUEUE
	LD	HL,PSK_INT		; INSTALL VECTOR
	LD	(IVT(INT_PS2KB)),HL	; IVT INDEX
#ENDIF
;
	LD	A,PSK_CON_WCR		; SET COMMAND REGISTER
	CALL	PSK_PUTCMD		; SEND IT

#IF ((INTMODE == 2) & PSKINTS)
	; TODO: INTS ONLY POSSIBLE ON PSK0
	LD	A,PSK_CON_ION		; XLAT DISABLED, MOUSE DISABLED, INTS ON		
#ELSE
	LD	A,PSK_CON_IOF		; XLAT DISABLED, MOUSE DISABLED, INTS OFF
#ENDIF
	CALL	PSK_PUTDATA		; SEND IT
	CALL	PSK_GETDATA		; GOBBLE UP $AA FROM POWER UP, AS NEEDED
	
	CALL 	PSK_RESET		; RESET THE KEYBOARD
	CALL	PSK_SETLEDS		; UPDATE LEDS BASED ON CURRENT TOGGLE STATE BITS
	CALL	PSK_SETRPT		; UPDATE REPEAT RATE BASED ON CURRENT SETTING

	PUSH	IY			; DE := INSTANCE DATA PTR
	POP	DE			; ... FROM CALLER'S IY
	CALL	KBD_ADDENT		; ADD ENTRY, A := UNIT ASSIGNED
	LD	(IY+CFG_UNIT),A		; RECORD HBIOS UNIT NUMBER ASSIGNED
	
	XOR	A			; SIGNAL SUCCESS
	RET
