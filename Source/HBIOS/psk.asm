PSK_STR_TAG	.TEXT	"PSK$"
;
; DRIVER FUNCTION TABLE
;
PSK_FNTBL:
	.DW	PSK_STAT
	.DW	PSK_FLUSH
	.DW	PSK_READ
	.DW	PSK_DEVICE
#IF (($ - PSK_FNTBL) != (KBD_FNCNT * 2))
