  #ENDIF
	DEVECHO ", IO="
	DEVECHO	PSK0_IO_DATA
  #IF ((PSKINTS) & (INTMODE > 0))
	DEVECHO	", INTERRUPTS ENABLED"
  #ENDIF
	DEVECHO	"\n"
#ENDIF
