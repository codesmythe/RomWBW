;
;__________________________________________________________________________________________________
; KEYBOARD STATUS
;__________________________________________________________________________________________________
;
PSK_STAT:
	CALL	PSK_DECODE		; CHECK THE KEYBOARD
	JP	Z,CIO_IDLE		; RET VIA IDLE PROCESSING IF NO KEY
	RET
;
;__________________________________________________________________________________________________
; KEYBOARD FLUSH
;__________________________________________________________________________________________________
;
PSK_FLUSH:
	XOR	A			; A = 0
	LD	(PSK_STATUS),A		; CLEAR STATUS
	RET
;
;__________________________________________________________________________________________________
; KEYBOARD READ
;
;   RETURNS ASCII VALUE IN E.  SEE END OF FILE FOR VALUES RETURNED FOR SPECIAL KEYS
;   LIKE PGUP, ARROWS, FUNCTION KEYS, ETC.
;__________________________________________________________________________________________________
;
PSK_READ:
	CALL	PSK_STAT		; KEY READY?
	JR	Z,PSK_READ		; NOT READY, KEEP TRYING
;
	LD	A,(PSK_STATUS)		; GET STATUS
	AND	$01			; ISOLATE EXTENDED SCANCODE BIT
	RRCA				; ROTATE IT TO HIGH ORDER BIT
	LD	E,A			; SAVE IT IN E FOR NOW
	LD	A,(PSK_SCANCODE)	; GET SCANCODE
	OR	E			; COMBINE WITH EXTENDED BIT
	LD	C,A			; STORE IT IN C FOR RETURN
	LD	A,(PSK_KEYCODE)		; GET KEYCODE
	LD	E,A			; SAVE IT IN E
	LD	A,(PSK_STATE)		; GET STATE FLAGS
	LD	D,A			; SAVE THEM IN D
	XOR	A			; SIGNAL SUCCESS
	LD	(PSK_STATUS),A		; CLEAR STATUS TO INDICATE BYTE RECEIVED
	RET
;
;__________________________________________________________________________________________________
; KEYBOARD DEVICE
;__________________________________________________________________________________________________
;
PSK_DEVICE:
	LD	D,KBDDEV_PSK		; DEVICE TYPE
	LD	E,(IY+CFG_DEVNUM)	; PHYSICAL UNIT
	XOR	A			; SIGNAL SUCCESS
	RET
;
;__________________________________________________________________________________________________
PSK_PUTCMD:
;
; PUT A CMD BYTE FROM A TO THE KEYBOARD INTERFACE WITH TIMEOUT
;
	LD	E,A			; SAVE INCOMING VALUE IN E
	LD	A,(IY+PSK_MODE)		; GET MODE BYTE
	CP	PSKMODE_VRC		; VGARC KEYBOARD?
	RET	Z			; BAIL OUT
	CALL	PSK_CHK_OST
PSK_PUTCMD1:
	LD	A,E			; RECOVER VALUE TO WRITE
#IF (PSKTRACE >= 2)
	CALL	PC_SPACE
	CALL	PC_GT
	CALL	PC_GT
	CALL	PRTHEXBYTE
#ENDIF
	JP	PSK_CMDOUT		; OUTPUT CMD TO PORT
;
;__________________________________________________________________________________________________
PSK_PUTDATA:
;
; PUT A DATA BYTE FROM A TO THE KEYBOARD INTERFACE WITH TIMEOUT
;
	LD	E,A			; SAVE INCOMING VALUE IN E
	LD	A,(IY+PSK_MODE)		; GET MODE BYTE
	CP	PSKMODE_VRC		; VGARC KEYBOARD?
	RET	Z			; BAIL OUT
	CALL	PSK_CHK_OST
PSK_PUTDATA1:
	LD	A,E			; RECOVER VALUE TO WRITE
#IF (PSKTRACE >= 2)
	CALL	PC_SPACE
	CALL	PC_GT
	CALL	PRTHEXBYTE
#ENDIF
	JP	PSK_DTAOUT		; WRITE IT
;
;__________________________________________________________________________________________________
;
; CHECK OUTPUT BUFFER IS READY TO ACCEPT. TIMEOUT IF BUFFER DOES NOT BECOME READY 
;
PSK_CHK_OST:
	LD	B,PSK_WAITTO		; SETUP TO LOOP
PSK_OST_LP:
	CALL	PSK_OST			; GET OUTPUT REGISTER STATUS
	RET	NZ			; EMPTY, GO TO WRITE
	CALL	DELAY			; WAIT A BIT
	DJNZ	PSK_OST_LP		; LOOP UNTIL COUNTER EXHAUSTED
	RET
;
;__________________________________________________________________________________________________
;
PSK_GETDATA_P:
;
; GET A RAW DATA BYTE FROM KEYBOARD INTERFACE INTO A WITH TIMEOUT.
; PSK_GETDATA_P ALWAYS READS A BYTE FROM THE KEYBOARD CONTROLLER PORT.
;
	LD	B,PSK_WAITTO		; SETUP TO LOOP
PSK_GETDATA0_P:
	CALL	PSK_IST_P		; GET INPUT REGISTER STATUS
	JR	NZ,PSK_GETDATA1_P	; BYTE PENDING, GO GET IT
	CALL	DELAY			; WAIT A BIT
	DJNZ	PSK_GETDATA0_P		; LOOP UNTIL COUNTER EXHAUSTED
	XOR	A			; NO DATA, RETURN ZERO
	RET
PSK_GETDATA1_P:
	CALL	PSK_IN_P		; GET A KEY
#IF (PSKTRACE >= 2)
	PUSH	AF
	CALL	PC_SPACE
	CALL	PC_LT
	CALL	PRTHEXBYTE
	POP	AF
#ENDIF
	OR	A			; SET FLAGS
	RET
;
PSK_GETDATA_Q:
;
; GET A QUEUED DATA BYTE FROM KEYBOARD INTERFACE INTO A WITH TIMEOUT.
; PSK_GETDATA_Q ALWAYS READS A BYTE FROM THE KEYBOARD INTERRUPT QUEUE.
;
#IF ((INTMODE == 2) & PSKINTS))
;
	LD	B,PSK_WAITTO		; SETUP TO LOOP
PSK_GETDATA0_Q:
	CALL	PSK_IST_Q		; GET INPUT REGISTER STATUS
	JR	NZ,PSK_GETDATA1_Q	; BYTE PENDING, GO GET IT
	CALL	DELAY			; WAIT A BIT
	DJNZ	PSK_GETDATA0_Q		; LOOP UNTIL COUNTER EXHAUSTED
	XOR	A			; NO DATA, RETURN ZERO
	RET
PSK_GETDATA1_Q:
	CALL	PSK_IN_Q		; GET A KEY
  #IF (PSKTRACE >= 2)
	PUSH	AF
	CALL	PC_SPACE
	CALL	PC_LT
	CALL	PRTHEXBYTE
	POP	AF
  #ENDIF
	OR	A			; SET FLAGS
	RET
;
#ENDIF
;
; GET A DATA BYTE FROM KEYBOARD INTERFACE INTO A WITH TIMEOUT.
; DEPENDING ON ASSEMBLY CONFIGURATION PSK_GETDATA READS A BYTE FROM 
; EITHER THE INTERRUPT QUEUE OR FROM THE KEYBOARD CONTROLLER PORT. 
;
#IF ((INTMODE == 2) & PSKINTS))
	; TODO: INTS ONLY POSSIBLE ON PSK0
PSK_GETDATA	.EQU	PSK_GETDATA_Q
PSK_GETDATA1	.EQU	PSK_GETDATA1_Q
#ELSE
PSK_GETDATA	.EQU	PSK_GETDATA_P
PSK_GETDATA1	.EQU	PSK_GETDATA1_P
#ENDIF
;
;__________________________________________________________________________________________________
PSK_GETDATAX:
;
; GET A DATA BYTE FROM KEYBOARD INTERFACE INTO A WITH NO TIMEOUT
; IF NOTHING AVAILABLE, RETURN 0.
;
	CALL	PSK_IST			; GET INPUT REGISTER STATUS
	RET	Z			; NOTHING THERE, DONE
	JR	PSK_GETDATA1		; GO GET IT
;
;__________________________________________________________________________________________________
; RESET KEYBOARD
;__________________________________________________________________________________________________
;
PSK_RESET:
	LD	A,$FF		; RESET COMMAND
	CALL	PSK_PUTDATA	; SEND IT
	CALL	PSK_GETDATA	; GET THE ACK
	LD	B,PSK_WAITTO	; SETUP LOOP COUNTER
PSK_RESET0:
	PUSH	BC		; PRESERVE COUNTER
	CALL	PSK_GETDATA	; TRY TO GET THE RESPONSE
	POP	BC		; RECOVER COUNTER
	JR	NZ,PSK_RESET1	; GOT A BYTE?  IF SO, GET OUT OF LOOP
	DJNZ	PSK_RESET0	; LOOP TILL COUNTER EXHAUSTED
PSK_RESET1:
	XOR	A		; SIGNAL SUCCESS (RESPONSE IS IGNORED...)
	RET			; DONE
;
;__________________________________________________________________________________________________
; UPDATE KEYBOARD LEDS BASED ON CURRENT TOGGLE FLAGS
;__________________________________________________________________________________________________
;
PSK_SETLEDS:
	LD	A,$ED		; SET/RESET LED'S COMMAND
	CALL	PSK_PUTDATA	; SEND THE COMMAND
	CALL	PSK_GETDATA	; READ THE RESPONSE
	CP	PSK_ACK		; MAKE SURE WE GET ACK
	RET	NZ		; ABORT IF NO ACK
	LD	A,(PSK_STATE)	; LOAD THE STATE BYTE
	RRCA			; ROTATE TOGGLE KEY BITS AS NEEDED
	RRCA
	RRCA
	RRCA
	AND	$07		; CLEAR THE IRRELEVANT BITS
	CALL	PSK_PUTDATA	; SEND THE LED DATA
	CALL	PSK_GETDATA	; READ THE ACK
	JP	PSK_DECNEW	; RESTART DECODER FOR A NEW KEY
	RET			; DONE
;
;__________________________________________________________________________________________________
; UPDATE KEYBOARD REPEAT RATE BASED ON CURRENT SETTING
;__________________________________________________________________________________________________
;
PSK_SETRPT:
	LD	A,$F3		; COMMAND = SET TYPEMATIC RATE/DELAY
	CALL	PSK_PUTDATA	; SEND IT
	CALL	PSK_GETDATA	; GET THE ACK
	CP	PSK_ACK		; MAKE SURE WE GET ACK
	RET	NZ		; ABORT IF NO ACK
	LD	A,(PSK_REPEAT)	; LOAD THE CURRENT RATE/DELAY BYTE
	CALL	PSK_PUTDATA	; SEND IT
	CALL	PSK_GETDATA	; GET THE ACK
	RET
;
;__________________________________________________________________________________________________
; DECODING ENGINE
;__________________________________________________________________________________________________
;
;__________________________________________________________________________________________________
PSK_DECODE:
;
;  RUN THE DECODING ENGINE UNTIL EITHER: 1) NO MORE SCANCODES ARE AVAILABLE
;  FROM THE KEYBOARD, OR 2) A DECODED KEY VALUE IS AVAILABLE
;
;  RETURNS A=0 AND Z SET IF NO KEYCODE READY, OTHERWISE A DECODED KEY VALUE IS AVAILABLE.
;  THE DECODED KEY VALUE AND KEY STATE IS STORED IN PSK_KEYCODE AND PSK_STATE.
;
;  PSK_STATUS IS NOT CLEARED AT START. IT IS THE CALLER'S RESPONSIBILITY
;  TO CLEAR PSK_STATUS WHEN IT HAS RETRIEVED A PENDING VALUE.  IF DECODE IS CALLED
;  WITH A KEYCODE STILL PENDING, IT WILL JUST RETURN WITHOUT DOING ANYTHING.
;
; Step 0: Check keycode buffer
;   if status[keyrdy]
;     return
; 
; Step 1: Get scancode
;   if no scancode ready
;     return
;   read scancode
;
; Step 2: Detect and handle special keycodes
;   if scancode == $AA
;     *** handle hot insert somehow ***
; 
; Step 3: Detect and handle scancode prefixes
;   if scancode == $E0
;     set status[extended]
;     goto Step 1
; 
;   if scancode == $E1
;     *** handle pause key somehow ***
; 
; Step 4: Detect and flag break event
;   *** scancode set #1 variation ***
;     set status[break] = high bit of scancode
;     clear high order bit
;     continue to Step 5
;   *** scancode set #2 variation ***
;     if scancode == $F0
;       set status[break]
;       goto Step 1
; 
; Step 5: Map scancode to keycode 
;   if status[extended]
;     apply extended-map[scancode] -> keycode
;   else if state[shifted]
;     apply shifted-map[scancode] -> keycode
;   else
;     apply normal-map[scancode] -> keycode
; 
; Step 6: Handle modifier keys
;   if keycode is modifier (shift, ctrl, alt, win)
;     set (l/r)state[<modifier>] = not status[break]
;     clear modifier bits in state
;     set state = (lstate OR rstate OR state)
;     goto New Key
; 
; Step 7: Complete procesing of key break events
;   if status[break]
;     goto New Key
; 
; Step 8: Handle toggle keys
;   if keycode is toggle (capslock, numlock, scrolllock)
;     invert (XOR) state[<toggle>]
;     update keyboard LED's
;     goto New Key
; 
; Step 9: Adjust keycode for control modifier
;   if state[ctrl]
;     if keycode is 'a'-'z'
;       subtract 20 (clear bit 5) from keycode
;     if keycode is '@'-'_'
;       subtract 40 (clear bit 6) from keycode
; 
; Step 10: Adjust keycode for caps lock
;   if state[capslock]
;     if keycode is 'a'-'z' OR 'A'-'Z'
;       toggle (XOR) bit 5 of keycode
; 
; Step 11: Handle num pad keys
;   clear state[numpad]
;   if keycode is numpad
;     set state[numpad]
;     if state[numlock]
;       toggle (XOR) bit 4 of keycode
;     apply numpad-map[keycode] -> keycode
; 
; Step 12: Detect unknown/invalid keycodes
;   if keycode == $FF
;     goto New Key
; 
; Step 13: Done
;   set status[keyrdy]
;   return
;
; New Key:
;   clear status
;   goto Step 1
;
PSK_DEC0:	; CHECK KEYCODE BUFFER
	LD	A,(PSK_STATUS)		; GET CURRENT STATUS
	AND	PSK_KEYRDY		; ISOLATE KEY READY FLAG
	RET	NZ			; ABORT IF KEY IS ALREADY PENDING

PSK_DEC1:	; PROCESS NEXT SCANCODE
	CALL	PSK_GETDATAX		; GET THE SCANCODE
	RET	Z			; NO KEY READY, RETURN WITH A=0, Z SET
	LD	(PSK_SCANCODE),A	; SAVE SCANCODE

;PSK_DEC2:	; DETECT AND HANDLE SPECIAL KEYCODES
;	LD	A,(PSK_SCANCODE)	; GET THE CURRENT SCANCODE
	CP	$AA			; KEYBOARD INSERTION?
	JR	NZ,PSK_DEC3		; NOPE, BYPASS
	CALL	LDELAY			; WAIT A BIT
	CALL	PSK_RESET		; RESET KEYBOARD
	CALL	PSK_SETLEDS		; SET LEDS
	CALL	PSK_SETRPT		; SET REPEAT RATE
	JP	PSK_DECNEW		; RESTART THE ENGINE

PSK_DEC3:	; DETECT AND HANDLE SCANCODE PREFIXES
	LD	A,(PSK_SCANCODE)	; GET THE CURRENT SCANCODE

PSK_DEC3A:	; HANDLE SCANCODE PREFIX $E0 (EXTENDED SCANCODE FOLLOWS)
	CP	$E0			; EXTENDED KEY PREFIX $E0?
	JR	NZ,PSK_DEC3B		; NOPE MOVE ON
	LD	A,(PSK_STATUS)		; GET STATUS
	OR	PSK_EXT			; SET EXTENDED BIT
	LD	(PSK_STATUS),A		; SAVE STATUS
	JR	PSK_DEC1		; LOOP TO DO NEXT SCANCODE

PSK_DEC3B:	; HANDLE SCANCODE PREFIX $E1 (PAUSE KEY)
	CP	$E1			; EXTENDED KEY PREFIX $E1
	JR	NZ,PSK_DEC4		; NOPE MOVE ON
	LD	A,$EE			; MAP TO KEYCODE $EE
	LD	(PSK_KEYCODE),A		; SAVE IT
		; SWALLOW NEXT 7 SCANCODES
	LD	B,7			; LOOP 5 TIMES
PSK_DEC3B1:
	PUSH	BC
	CALL	PSK_GETDATA		; RETRIEVE NEXT SCANCODE
	POP	BC
	DJNZ	PSK_DEC3B1		; LOOP AS NEEDED
	JP	PSK_DEC6		; RESUME AFTER MAPPING

PSK_DEC4:	; DETECT AND FLAG BREAK EVENT
	CP	$F0			; BREAK (KEY UP) PREFIX?
	JR	NZ,PSK_DEC5		; NOPE MOVE ON
	LD	A,(PSK_STATUS)		; GET STATUS
	OR	PSK_BREAK		; SET BREAK BIT
	LD	(PSK_STATUS),A		; SAVE STATUS
	JR	PSK_DEC1		; LOOP TO DO NEXT SCANCODE

PSK_DEC5:	; MAP SCANCODE TO KEYCODE
	LD	A,(PSK_STATUS)		; GET STATUS
	AND	PSK_EXT			; EXTENDED BIT SET?
	JR	Z,PSK_DEC5C		; NOPE, MOVE ON

		; PERFORM EXTENDED KEY MAPPING
	LD	A,(PSK_SCANCODE)	; GET SCANCODE
	LD	E,A			; STASH IT IN E
	LD	HL,PSK_MAPEXT		; POINT TO START OF EXT MAP TABLE
PSK_DEC5A:
	LD	A,(HL)			; GET FIRST BYTE OF PAIR
	CP	$00			; END OF TABLE?
	JP	Z,PSK_DECNEW		; UNKNOWN OR BOGUS, START OVER
	INC	HL			; INC HL FOR FUTURE
	CP	E			; DOES MATCH BYTE EQUAL SCANCODE?
	JR	Z,PSK_DEC5B		; YES! JUMP OUT
	INC	HL			; BUMP TO START OF NEXT PAIR
	JR	PSK_DEC5A		; LOOP TO CHECK NEXT TABLE ENTRY
PSK_DEC5B:
	LD	A,(HL)			; GET THE KEYCODE VIA MAPPING TABLE
	LD	(PSK_KEYCODE),A		; SAVE IT
	JR	PSK_DEC6

PSK_DEC5C:	; PERFORM REGULAR KEY (NOT EXTENDED) KEY MAPPING
	LD	A,(PSK_SCANCODE)	; GET THE SCANCODE
	CP	PSK_MAPSIZ		; COMPARE TO SIZE OF TABLE
	JR	NC,PSK_DEC6		; PAST END, SKIP OVER LOOKUP

		; SETUP POINTER TO MAPPING TABLE BASED ON SHIFTED OR UNSHIFTED STATE
	LD	A,(PSK_STATE)		; GET STATE
	AND	KBD_SHIFT		; SHIFT ACTIVE?
	LD	HL,PSK_MAPSTD		; LOAD ADDRESS OF NON-SHIFTED MAPPING TABLE
	JR	Z,PSK_DEC5D		; NON-SHIFTED, MOVE ON
	LD	HL,PSK_MAPSHIFT		; LOAD ADDRESS OF SHIFTED MAPPING TABLE
PSK_DEC5D:
	LD	A,(PSK_SCANCODE)	; GET THE SCANCODE
	LD	E,A			; SCANCODE TO E FOR TABLE OFFSET
	LD	D,0			; D -> 0
	ADD	HL,DE			; COMMIT THE TABLE OFFSET TO HL
	LD	A,(HL)			; GET THE KEYCODE VIA MAPPING TABLE
	LD	(PSK_KEYCODE),A		; SAVE IT

PSK_DEC6:	; HANDLE MODIFIER KEYS
	LD	A,(PSK_KEYCODE)		; MAKE SURE WE HAVE KEYCODE
	CP	$B8			; END OF MODIFIER KEYS
	JR	NC,PSK_DEC7		; BYPASS MODIFIER KEY CHECKING
	CP	$B0			; START OF MODIFIER KEYS
	JR	C,PSK_DEC7		; BYPASS MODIFIER KEY CHECKING
	
	LD	B,4			; LOOP COUNTER TO LOOP THRU 4 MODIFIER BITS
	LD	E,$80			; SETUP E TO ROATE THROUGH MODIFIER STATE BITS
	SUB	$B0 - 1			; SETUP A TO DECREMENT THROUGH MODIFIER VALUES
	
PSK_DEC6A:
	RLC	E			; SHIFT TO NEXT MODIFIER STATE BIT
	DEC	A			; L-MODIFIER?
	JR	Z,PSK_DEC6B		; YES, HANDLE L-MODIFIER MAKE/BREAK
	DEC	A			; R-MODIFIER?
	JR	Z,PSK_DEC6C		; YES, HANDLE R-MODIFIER MAKE/BREAK
	DJNZ	PSK_DEC6A		; LOOP THRU 4 MODIFIER BITS
	JR	PSK_DEC7		; FAILSAFE, SHOULD NEVER GET HERE!

PSK_DEC6B:	; LEFT STATE KEY MAKE/BREAK (STATE BIT TO SET/CLEAR IN E)
	LD	HL,PSK_LSTATE		; POINT TO LEFT STATE BYTE
	JR	PSK_DEC6D		; CONTINUE

PSK_DEC6C:	; RIGHT STATE KEY MAKE/BREAK (STATE BIT TO SET/CLEAR IN E)
	LD	HL,PSK_RSTATE		; POINT TO RIGHT STATE BYTE
	JR	PSK_DEC6D		; CONTINUE
	
PSK_DEC6D:	; BRANCH BASED ON WHETHER THIS IS A MAKE OR BREAK EVENT
	LD	A,(PSK_STATUS)		; GET STATUS FLAGS
	AND	PSK_BREAK		; BREAK EVENT?
	JR	Z,PSK_DEC6E		; NO, HANDLE A MODIFIER KEY MAKE EVENT
	JR	PSK_DEC6F		; YES, HANDLE A MODIFIER BREAK EVENT

PSK_DEC6E:	; HANDLE STATE KEY MAKE EVENT
	LD	A,E			; GET THE BIT TO SET
	OR	(HL)			; OR IN THE CURRENT BITS
	LD	(HL),A			; SAVE THE RESULT
	JR	PSK_DEC6G		; CONTINUE

PSK_DEC6F:	; HANDLE STATE KEY BREAK EVENT
	LD	A,E			; GET THE BIT TO CLEAR
	XOR	$FF			; FLIP ALL BITS TO SETUP FOR A CLEAR OPERATION
	AND	(HL)			; AND IN THE FLIPPED BITS TO CLEAR DESIRED BIT
	LD	(HL),A			; SAVE THE RESULT
	JR	PSK_DEC6G		; CONTINUE
	
PSK_DEC6G:	; COALESCE L/R STATE FLAGS
	LD	A,(PSK_STATE)		; GET EXISTING STATE BITS
	AND	$F0			; GET RID OF OLD MODIFIER BITS
	LD	DE,(PSK_LSTATE)		; LOAD BOTH L/R STATE BYTES IN D/E
	OR	E			; MERGE IN LEFT STATE BITS
	OR	D			; MERGE IN RIGHT STATE BITS
	LD	(PSK_STATE),A		; SAVE IT
	JP	PSK_DECNEW		; DONE WITH CURRENT KEYSTROKE

PSK_DEC7:	; COMPLETE PROCESSING OF EXTENDED AND KEY BREAK EVENTS
	LD	A,(PSK_STATUS)		; GET CURRENT STATUS FLAGS
	AND	PSK_BREAK		; IS THIS A KEY BREAK EVENT?
	JP	NZ,PSK_DECNEW		; PROCESS NEXT KEY

PSK_DEC8:	; HANDLE TOGGLE KEYS
	LD	A,(PSK_KEYCODE)		; GET THE CURRENT KEYCODE INTO A
	LD	E,KBD_CAPSLCK		; SETUP E WITH CAPS LOCK STATE BIT
	CP	$BC			; IS THIS THE CAPS LOCK KEY?
	JR	Z,PSK_DEC8A		; YES, GO TO BIT SET ROUTINE
	LD	E,KBD_NUMLCK		; SETUP E WITH NUM LOCK STATE BIT
	CP	$BD			; IS THIS THE NUM LOCK KEY?
	JR	Z,PSK_DEC8A		; YES, GO TO BIT SET ROUTINE
	LD	E,KBD_SCRLCK		; SETUP E WITH SCROLL LOCK STATE BIT
	CP	$BE			; IS THIS THE SCROLL LOCK KEY?
	JR	Z,PSK_DEC8A		; YES, GO TO BIT SET ROUTINE
	JR	PSK_DEC9		; NOT A TOGGLE KEY, CONTINUE
	
PSK_DEC8A:	; RECORD THE TOGGLE
	LD	A,(PSK_STATE)		; GET THE CURRENT STATE FLAGS
	XOR	E			; SET THE TOGGLE KEY BIT FROM ABOVE
	LD	(PSK_STATE),A		; SAVE IT
	CALL	PSK_SETLEDS		; UPDATE LED LIGHTS ON KBD
	JP	PSK_DECNEW		; RESTART DECODER FOR A NEW KEY

PSK_DEC9:	; ADJUST KEYCODE FOR CONTROL MODIFIER
	LD	A,(PSK_STATE)		; GET THE CURRENT STATE BITS
	AND	KBD_CTRL		; CHECK THE CONTROL BIT
	JR	Z,PSK_DEC10		; CONTROL KEY NOT PRESSED, MOVE ON
	LD	A,(PSK_KEYCODE)		; GET CURRENT KEYCODE IN A
	CP	'a'			; COMPARE TO LOWERCASE A
	JR	C,PSK_DEC9A		; BELOW IT, BYPASS
	CP	'z' + 1			; COMPARE TO LOWERCASE Z
	JR	NC,PSK_DEC9A		; ABOVE IT, BYPASS
	RES	5,A			; KEYCODE IN LOWERCASE A-Z RANGE CLEAR BIT 5 TO MAKE IT UPPERCASE
PSK_DEC9A:
	CP	'@'			; COMPARE TO @
	JR	C,PSK_DEC10		; BELOW IT, BYPASS
	CP	'_' + 1			; COMPARE TO _
	JR	NC,PSK_DEC10		; ABOVE IT, BYPASS
	RES	6,A			; CONVERT TO CONTROL VALUE BY CLEARING BIT 6
	LD	(PSK_KEYCODE),A		; UPDATE KEYCODE TO CONTROL VALUE

PSK_DEC10:	; ADJUST KEYCODE FOR CAPS LOCK
	LD	A,(PSK_STATE)		; LOAD THE STATE FLAGS
	AND	KBD_CAPSLCK		; CHECK CAPS LOCK
	JR	Z,PSK_DEC11		; CAPS LOCK NOT ACTIVE, MOVE ON
	LD	A,(PSK_KEYCODE)		; GET THE CURRENT KEYCODE VALUE
	CP	'a'			; COMPARE TO LOWERCASE A
	JR	C,PSK_DEC10A		; BELOW IT, BYPASS
	CP	'z' + 1			; COMPARE TO LOWERCASE Z
	JR	NC,PSK_DEC10A		; ABOVE IT, BYPASS
	JR	PSK_DEC10B		; IN RANGE LOWERCASE A-Z, GO TO CASE SWAPPING LOGIC
PSK_DEC10A:
	CP	'A'			; COMPARE TO UPPERCASE A
	JR	C,PSK_DEC11		; BELOW IT, BYPASS
	CP	'Z' + 1			; COMPARE TO UPPERCASE Z
	JR	NC,PSK_DEC11		; ABOVE IT, BYPASS
	JR	PSK_DEC10B		; IN RANGE UPPERCASE A-Z, GO TO CASE SWAPPING LOGIC
PSK_DEC10B:
	LD	A,(PSK_KEYCODE)		; GET THE CURRENT KEYCODE
	XOR	$20			; FLIP BIT 5 TO SWAP UPPER/LOWER CASE
	LD	(PSK_KEYCODE),A		; SAVE IT

PSK_DEC11:	; HANDLE NUM PAD KEYS
	LD	A,(PSK_STATE)		; GET THE CURRENT STATE FLAGS
	AND	~KBD_NUMPAD		; ASSUME NOT A NUMPAD KEY, CLEAR THE NUMPAD BIT
	LD	(PSK_STATE),A		; SAVE IT
	
	LD	A,(PSK_KEYCODE)		; GET THE CURRENT KEYCODE
	AND	11100000B		; ISOLATE TOP 3 BITS
	CP	11000000B		; IS IN NUMPAD RANGE?
	JR	NZ,PSK_DEC12		; NOPE, GET OUT
	
	LD	A,(PSK_STATE)		; LOAD THE CURRENT STATE FLAGS
	OR	KBD_NUMPAD		; TURN ON THE NUMPAD BIT
	LD	(PSK_STATE),A		; SAVE IT

	AND	KBD_NUMLCK		; IS NUM LOCK BIT SET?
	JR	Z,PSK_DEC11A		; NO, SKIP NUMLOCK PROCESSING
	LD	A,(PSK_KEYCODE)		; GET THE KEYCODE
	XOR	$10			; FLIP VALUES FOR NUMLOCK
	LD	(PSK_KEYCODE),A		; SAVE IT

PSK_DEC11A:	; APPLY NUMPAD MAPPING
	LD	A,(PSK_KEYCODE)		; GET THE CURRENT KEYCODE
	LD	HL,PSK_MAPNUMPAD	; LOAD THE START OF THE MAPPING TABLE
	SUB	$C0			; KEYCODES START AT $C0
	LD	E,A			; INDEX TO E
	LD	D,0			; D IS ZERO
	ADD	HL,DE			; POINT TO RESULT OF MAPPING
	LD	A,(HL)			; GET IT IN A
	LD	(PSK_KEYCODE),A		; SAVE IT

PSK_DEC12:	; DETECT UNKNOWN/INVALID KEYCODES
	LD	A,(PSK_KEYCODE)		; GET THE FINAL KEYCODE
	CP	$FF			; IS IT $FF (UNKNOWN/INVALID)
	JP	Z,PSK_DECNEW		; IF SO, JUST RESTART THE ENGINE

PSK_DEC13:	; DONE - RECORD RESULTS
	LD	A,(PSK_STATUS)		; GET CURRENT STATUS
	OR	PSK_KEYRDY		; SET KEY READY BIT
	LD	(PSK_STATUS),A		; SAVE IT
	XOR	A			; A=0
	INC	A			; SIGNAL SUCCESS WITH A=1
	RET
	
PSK_DECNEW:	; START NEW KEYPRESS (CLEAR ALL STATUS BITS)
	XOR	A			; A = 0
	LD	(PSK_STATUS),A		; CLEAR STATUS
	JP	PSK_DEC1		; RESTART THE ENGINE
;
