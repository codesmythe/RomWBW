#IF (PSKCNT >= 2)
	.DW	PSK_FNTBL		; DRIVER FUNCTION TABLE ADDRESS				
	.DB	'K'			; DRIVER TYPE						
	.DB	$FF			; HBIOS UNIT NUMBER (FILLED DYNAMICALLY, $FF=NONE)	
	.DB	1			; DRIVER UNIT NUMBER
	.DB	ERR_NONE		; DEVICE STATUS (HBIOS STATUS)				
