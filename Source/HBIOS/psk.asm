;__________________________________________________________________________________________________
; DATA CONSTANTS
;__________________________________________________________________________________________________
;
; DRIVER DATA OFFSETS (FROM IY)
;
; THE KEYBOARD PRIVATE CONFIG
; STARTS AT CFG_KBD, JUST AFTER THE 8 BYTE STANDARD HEADER (SEE
; STD.ASM DRIVER CONFIG BLOCK STANDARD OFFSETS).
;
PSK_MODE	.EQU	CFG_KBD + 0	; BYTE, KEYBOARD MODE (SEE STD.ASM PSKMODE_...)
PSK_DAT		.EQU	CFG_KBD + 1	; BYTE, DATA PORT NUM (R/W)
PSK_ST		.EQU	CFG_KBD + 2	; BYTE, STATUS PORT NUM (R)
PSK_CMD		.EQU	PSK_ST		; BYTE, CMD PORT NUM (W)
;
PSK_CFGSIZ	.EQU	11
;
; TIMING CONSTANTS
;
PSK_WAITTO	.EQU	0	; 0 IS MAX WAIT (256)
;
; STATUS BITS (FOR PSK_STATUS)
;
PSK_EXT		.EQU	01H	; BIT 0, EXTENDED SCANCODE ACTIVE
PSK_BREAK	.EQU	02H	; BIT 1, THIS IS A KEY UP (BREAK) EVENT
PSK_KEYRDY	.EQU	80H	; BIT 7, INDICATES A DECODED KEYCODE IS READY
;
PSK_DEFRPT	.EQU	$40		; DEFAULT REPEAT RATE (.5 SEC DELAY, 30CPS)
PSK_DEFSTATE	.EQU	KBD_NUMLCK	; DEFAULT STATE (NUM LOCK ON)
PSK_ACK		.EQU	$FA		; CMD ACKNOWLEDGE
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_PSK	.EQU	$
;
	.DW	SIZ_PSK			; MODULE SIZE
	.DW	PSK_INITPHASE		; ADR OF INIT PHASE HANDLER
;
PSK_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,PSK_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,PSK_INIT		; DO INIT
	RET				; DONE
;__________________________________________________________________________________________________
; DATA
;__________________________________________________________________________________________________
;
PSK_SCANCODE	.DB	0	; RAW SCANCODE
PSK_KEYCODE	.DB	0	; RESULTANT KEYCODE AFTER DECODING
PSK_STATE	.DB	0	; STATE BITS (SEE ABOVE)
PSK_LSTATE	.DB	0	; STATE BITS FOR "LEFT" KEYS
PSK_RSTATE	.DB	0	; STATE BITS FOR "RIGHT" KEYS
PSK_STATUS	.DB	0	; CURRENT STATUS BITS (SEE ABOVE)
PSK_REPEAT	.DB	0	; CURRENT REPEAT RATE
PSK_IDLE	.DB	0	; IDLE COUNT
;__________________________________________________________________________________________________
; 8242 CONTROLLER COMMANDS AND RESPONSES 
;__________________________________________________________________________________________________
;
PSK_CON_DP1	.EQU	$AD	; DISABLE PS2 PORT 1 (KEYBOARD)
PSK_CON_DP2	.EQU	$A7	; DISABLE PS2 PORT 2 (MOUSE)
PSK_CON_EP1	.EQU	$AE	; ENABLE PS2 PORT 1 (KEYBOARD)
PSK_CON_EP2	.EQU	$A8	; ENABLE PS2 PORT 2 (MOUSE)
PSK_CON_WCR	.EQU	$60	; WRITE TO COMMAND REGISTER. VALUE TO FOLLOW.
PSK_CON_CST	.EQU	$AA	; CONTROLLER SELF TEST. RETURN FF IF CONTROLLER OK
;__________________________________________________________________________________________________
; 8242 CONTROLLER COMMAND REGISTER VALUES
;__________________________________________________________________________________________________
;
PSK_CON_ION	.EQU	$21	; XLAT DISABLED, MOUSE DISABLED, WITH INTS		
PSK_CON_IOF	.EQU	$20	; XLAT DISABLED, MOUSE DISABLED, NO INTS
